import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {randomUUID} from 'node:crypto';
import {projectSchema} from '../server/projects.ts';
import {verificationPlan,establishVerification} from '../server/verification.ts';
import {parseReply} from '../server/codex-worker.ts';
test('an empty project can be registered but cannot establish an empty or malformed verification plan',()=>{
  const project=projectSchema.parse({id:'new',name:'New',kind:'repository',path:'.',reviewChecklist:'Review acceptance criteria.'});
  const root=resolve('.state/verification-tests',randomUUID());mkdirSync(root,{recursive:true});
  assert.deepEqual(verificationPlan(project,root),[]);
  assert.throws(()=>establishVerification(root,[]));
  assert.throws(()=>establishVerification(root,[{executable:'node',args:'--test'}]));
  const commands=[{executable:'node',args:['--test','app.test.mjs'],sandbox:'read-only' as const}];
  establishVerification(root,commands);assert.deepEqual(verificationPlan(project,root),commands);
  assert.throws(()=>establishVerification(root,[{...commands[0],args:['--test','other.test.mjs']}]));
  assert.deepEqual(verificationPlan(project,root),commands);
  assert.throws(()=>parseReply('implementing',{action:'implemented',summary:'Built',blockerKind:'none'},true));
  assert.throws(()=>parseReply('reviewing',{action:'approved',summary:'Reviewed',blockerKind:'none',verificationCommands:commands}));
});
